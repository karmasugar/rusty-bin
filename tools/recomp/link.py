import argparse
import pathlib
import sys

from hashing import fnv1a64

ENGLISH_PREFIX = "en_"


def find_game_file(directory: pathlib.Path, stem: str) -> pathlib.Path:
    matches = [path for path in directory.iterdir() if path.is_file() and path.stem.upper() == stem.upper()]
    if len(matches) != 1:
        raise SystemExit(f"link.py: {len(matches)} files for module {stem} in {directory}")
    return matches[0]


def module_files(modules: list[str], game_dirs: dict[str, pathlib.Path]) -> list[tuple[str, str, int]]:
    rows = []
    for module in modules:
        english = module.startswith(ENGLISH_PREFIX)
        directory = game_dirs.get("en" if english else "ja")
        if directory is None:
            continue
        path = find_game_file(directory, module.removeprefix(ENGLISH_PREFIX))
        rows.append((module, path.name.upper(), fnv1a64(path.read_bytes())))
    return rows


def link_source(
    modules: list[str], *, main: str, drivers: list[str], files: list[tuple[str, str, int]] | None = None
) -> str:
    lines = ["/* Generated by tools/recomp/link.py. Do not edit. */", '#include "rt.h"', ""]
    lines += [f"extern const RtModule {module}_module;" for module in modules]
    lines += ["", "const RtModule *const rt_modules[] = {"]
    lines += [f"    &{module}_module," for module in modules]
    lines += ["    0,", "};", "", f"const RtModule *const rt_main_module = &{main}_module;", ""]
    lines += ["const char *const rt_drivers[] = {"]
    lines += [f'    "{driver}",' for driver in drivers]
    lines += ["    0,", "};", ""]
    lines += ["const RtModuleFile rt_module_files[] = {"]
    lines += [f'    {{&{module}_module, "{name}", 0x{value:016x}ull}},' for module, name, value in files or []]
    lines += ["    {0, 0, 0},", "};", ""]
    return "\n".join(lines)


def parse_game_dir(text: str) -> tuple[str, pathlib.Path]:
    version, separator, directory = text.partition("=")
    if not separator or version not in ("ja", "en"):
        raise argparse.ArgumentTypeError(f"expected ja=DIR or en=DIR, got {text}")
    return version, pathlib.Path(directory)


def main() -> int:
    parser = argparse.ArgumentParser(description="Write the link table of recompiled modules and the start program.")
    parser.add_argument("modules", nargs="+", help="module prefixes; the first one is the program to start")
    parser.add_argument(
        "--driver", action="append", default=[], help='resident driver to run first, e.g. "PDR.COM /i" (repeatable)'
    )
    parser.add_argument(
        "--game-dir",
        action="append",
        type=parse_game_dir,
        default=[],
        help="ja=DIR or en=DIR: original game files; their hashes select the modules at run time (en_ modules: en)",
    )
    parser.add_argument("--out", type=pathlib.Path, required=True)
    args = parser.parse_args()
    files = module_files(args.modules, dict(args.game_dir))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(link_source(args.modules, main=args.modules[0], drivers=args.driver, files=files))
    return 0


if __name__ == "__main__":
    sys.exit(main())
