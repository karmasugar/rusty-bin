import argparse
import collections
import pathlib
import re
import struct
import sys
from dataclasses import dataclass, field

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
GENERATED_DIR = ROOT / "build/linux-dev/gen"
NAMES_DIR = ROOT / "tools/recomp/names"
HEADER = re.compile(r"^/\* Generated by tools/recomp/recomp.py from (\S+)\. Do not edit\. \*/$")
ENTRY = re.compile(r"^    \{0x([0-9a-f]{4}), 0x([0-9a-f]{4}), (\w+), ")
ENTRIES_START = re.compile(r"^const RtEntry (\w+)_entries\[\] = \{$")
FUNCTION = re.compile(r"^static void (\w+)\(Cpu \*c\)$")
INSTRUCTION = re.compile(r"^    /\* ([0-9a-f]{4}): (.*) \*/$")
NOTE = re.compile(r"^\s*/\* (.*) \*/$")
BRANCH = re.compile(r"^(j\w+|loop\w*|call) (0x[0-9a-f]+)$")
WORD_CONSTANT = re.compile(r"0x[0-9a-f]{3,4}\b")
ANY_CONSTANT = re.compile(r"0x[0-9a-f]+")
MIN_EXACT_SIZE = 3
JO_IMAGE = ROOT / "build/unpacked/ja/JO.EXE"
SERVICE_TABLES = {"call_service": (0x6360, 78), "call_enemy_service": (0x4540, 56)}
OBJECT_TYPE = ROOT / "tools/recomp/types/Object.tsv"
UNPACKED_DIR = ROOT / "build/unpacked/ja"
MIN_LOOSE_SIZE = 6
MIN_MASKED_SIZE = 8
TIER_NOTES = ("", ", data addresses differ", ", constants differ", ", same address in a sibling overlay")


@dataclass
class Function:
    module: str
    segment: int
    address: int
    name: str
    named: bool
    instructions: list[tuple[int, str]] = field(default_factory=list)

    @property
    def key(self) -> tuple[int, int]:
        return (self.segment, self.address)

    def label(self) -> str:
        return f"{self.segment:04X}:{self.address:04X}"

    def targets(self) -> list[tuple[str, int]]:
        found = []
        for _, text in self.instructions:
            match = BRANCH.match(text)
            if match:
                found.append((match.group(1), int(match.group(2), 16)))
            elif text.startswith("jmp 0x"):
                found.append(("jmp", int(text[4:], 16)))
        return found


@dataclass
class Module:
    file: str
    prefix: str
    functions: dict[tuple[int, int], Function] = field(default_factory=dict)

    def by_name(self, text: str) -> Function | None:
        for function in self.functions.values():
            if function.name == text or function.label() == text.upper() or f"{function.address:04x}" == text.lower():
                return function
        return None


def generated_files() -> list[pathlib.Path]:
    return sorted(GENERATED_DIR.glob("*_gen.c"), key=lambda path: (path.name.startswith("en_"), path.name))


def parse_generated(path: pathlib.Path) -> Module | None:
    lines = path.read_text(encoding="utf-8").splitlines()
    header = HEADER.match(lines[0]) if lines else None
    if not header:
        return None
    bodies: dict[str, list[tuple[int, str]]] = {}
    current = None
    module = Module(file=header.group(1), prefix="")
    in_entries = False
    for line in lines:
        match = FUNCTION.match(line)
        if match:
            current = bodies.setdefault(match.group(1), [])
            continue
        if line == "}":
            current = None
            continue
        match = INSTRUCTION.match(line)
        if match and current is not None:
            current.append((int(match.group(1), 16), match.group(2)))
            continue
        match = ENTRIES_START.match(line)
        if match:
            module.prefix = match.group(1)
            in_entries = True
            continue
        match = ENTRY.match(line) if in_entries else None
        if match:
            segment, address, name = int(match.group(1), 16), int(match.group(2), 16), match.group(3)
            unnamed = re.fullmatch(rf"{module.prefix}_[0-9a-f]{{4}}(_[0-9a-f]{{4}})?", name) is not None
            function = Function(module.file, segment, address, name, not unnamed, bodies.get(name, []))
            module.functions[function.key] = function
    return module


def load_modules() -> dict[str, Module]:
    modules = {}
    for path in generated_files():
        module = parse_generated(path)
        if module and module.file not in modules:
            modules[module.file] = module
    return modules


def fingerprint(function: Function, *, tier: int) -> tuple[str, ...]:
    start = function.address
    out = []
    for _, text in function.instructions:
        match = BRANCH.match(text)
        if match:
            kind, target = match.group(1), int(match.group(2), 16)
            out.append(f"{kind} {'CALL' if kind == 'call' else target - start}")
        elif tier == 1:
            out.append(WORD_CONSTANT.sub("X", text))
        elif tier == 2:
            out.append(ANY_CONSTANT.sub("X", text))
        else:
            out.append(text)
    return tuple(out)


def names_file(module: str) -> pathlib.Path:
    return NAMES_DIR / f"{module}.tsv"


def descriptions(module: str) -> dict[tuple[int, int], str]:
    path = names_file(module)
    found = {}
    if not path.exists():
        return found
    for line in path.read_text(encoding="utf-8").splitlines():
        columns = line.split("\t")
        if line.startswith("#") or len(columns) < 3 or columns[1] != "func":
            continue
        segment, offset = (int(part, 16) for part in columns[0].split(":"))
        found[(segment, offset)] = columns[3] if len(columns) > 3 else ""
    return found


def append_names(module: str, lines: list[str]) -> None:
    path = names_file(module)
    path.parent.mkdir(parents=True, exist_ok=True)
    text = path.read_text(encoding="utf-8") if path.exists() else f"# Names for {module}.\n"
    if not text.endswith("\n"):
        text += "\n"
    path.write_text(text + "\n".join(lines) + "\n", encoding="utf-8")


def inner_parent(module: Module, function: Function) -> Function | None:
    parents = [
        other
        for other in module.functions.values()
        if other.named
        and other.segment == function.segment
        and other.address < function.address
        and any(address == function.address for address, _ in other.instructions)
    ]
    return max(parents, key=lambda other: other.address) if parents else None


def propagate(modules: dict[str, Module], *, write: bool) -> int:
    groups: dict[tuple[int, tuple[str, ...]], list[Function]] = collections.defaultdict(list)
    for module in modules.values():
        family = re.sub(r"\d+\.", ".", module.file)
        for function in module.functions.values():
            if function.instructions and family != module.file:
                groups[(3, (family, function.label(), *fingerprint(function, tier=0)))].append(function)
            size = len(function.instructions)
            for tier, minimum in enumerate((MIN_EXACT_SIZE, MIN_LOOSE_SIZE, MIN_MASKED_SIZE)):
                if size >= minimum:
                    groups[(tier, fingerprint(function, tier=tier))].append(function)
    texts = {name: descriptions(name) for name in modules}
    taken = {name: {function.name for function in module.functions.values()} for name, module in modules.items()}
    new_lines: dict[str, list[str]] = collections.defaultdict(list)
    assigned: set[tuple[str, int, int]] = set()
    for (tier, _), members in sorted(groups.items(), key=lambda item: item[0][0]):
        names = {function.name for function in members if function.named}
        if len(names) != 1:
            continue
        source_name = names.pop()
        source = next(function for function in members if function.named)
        source_prefix = f"{modules[source.module].prefix}_"
        text = texts[source.module].get(source.key, "")
        for function in members:
            name = source_name
            if name.startswith(source_prefix):
                name = f"{modules[function.module].prefix}_{name[len(source_prefix) :]}"
            marker = (function.module, *function.key)
            if function.named or marker in assigned or name in taken[function.module]:
                continue
            assigned.add(marker)
            taken[function.module].add(name)
            origin = f"same code as {source.module} {source.label()}{TIER_NOTES[tier]}"
            new_lines[function.module].append(
                f"{function.label()}\tfunc\t{name}\t{text + ' ' if text else ''}({origin})"
            )
    for module in modules.values():
        for function in module.functions.values():
            marker = (function.module, *function.key)
            if function.named or marker in assigned:
                continue
            parent = inner_parent(module, function)
            if parent is None:
                continue
            name = f"{parent.name}_at_{function.address:04x}"
            if name in taken[module.file]:
                continue
            assigned.add(marker)
            taken[module.file].add(name)
            new_lines[module.file].append(
                f"{function.label()}\tfunc\t{name}\tEntry inside {parent.name}: the same code from this address."
            )
    for module, lines in sorted(new_lines.items()):
        print(f"{module}: {len(lines)} names")
        if write:
            append_names(module, lines)
    return sum(len(lines) for lines in new_lines.values())


def callers_of(module: Module) -> dict[tuple[int, int], list[Function]]:
    callers: dict[tuple[int, int], list[Function]] = collections.defaultdict(list)
    for function in module.functions.values():
        for kind, target in function.targets():
            key = (function.segment, target)
            if key in module.functions and key != function.key and (kind in ("call", "jmp")):
                callers[key].append(function)
    return callers


DATA_OPERAND = re.compile(r"(byte|word) ptr (cs:)?\[0x([0-9a-f]+)\]")
WRITING = {"mov", "add", "sub", "adc", "sbb", "and", "or", "xor", "inc", "dec", "not", "neg", "pop", "xchg"}
WRITING |= {"shl", "shr", "sar", "rol", "ror", "rcl", "rcr"}


def data_names(module: str, *, segment_register: str = "ds") -> dict[int, str]:
    names = {}
    base = module.removeprefix("en/")
    exe = base.upper().endswith(".EXE")
    for path in (names_file(base), NAMES_DIR / "en" / f"{base}.tsv"):
        if not path.exists():
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            columns = line.split("\t")
            if len(columns) < 3 or columns[1] != "data" or line.startswith("#"):
                continue
            segment, offset = (int(part, 16) for part in columns[0].split(":"))
            own_image = segment == 0
            if segment_register == "cs" and own_image or segment_register == "ds" and own_image != exe:
                names[offset] = columns[2]
    return names


def data_todo(module: Module) -> None:
    named = {"ds": data_names(module.file), "cs": data_names(module.file, segment_register="cs")}
    uses: dict[tuple[str, int], dict[str, set[str] | int | str]] = {}
    for function in module.functions.values():
        for _, text in function.instructions:
            mnemonic = text.split(" ")[0]
            for match in DATA_OPERAND.finditer(text):
                register = "cs" if match.group(2) else "ds"
                offset = int(match.group(3), 16)
                if offset in named[register]:
                    continue
                entry = uses.setdefault(
                    (register, offset), {"reads": 0, "writes": 0, "size": match.group(1), "users": set()}
                )
                first_operand = "," not in text or match.start() < text.index(",")
                if mnemonic in WRITING and first_operand:
                    entry["writes"] += 1
                if mnemonic != "mov" or not first_operand:
                    entry["reads"] += 1
                entry["users"].add(function.name if function.named else function.label())
    count = len(set(named["ds"]) | set(named["cs"]))
    print(f"{module.file}: {len(uses)} unnamed data addresses ({count} named)")
    for (register, offset), entry in sorted(uses.items(), key=lambda item: -(item[1]["reads"] + item[1]["writes"])):
        users = sorted(entry["users"])
        more = f" (+{len(users) - 6})" if len(users) > 6 else ""
        print(
            f"{register}:{offset:04X} {entry['size']:4} {entry['reads']:3} reads {entry['writes']:3} writes  "
            f"{', '.join(users[:6])}{more}"
        )


def todo(module: Module) -> None:
    callers = callers_of(module)
    unnamed = [function for function in module.functions.values() if not function.named]
    pending = {function.key for function in unnamed}
    order = []
    while pending:
        ready = [
            key
            for key in sorted(pending)
            if not any(
                (module.functions[key].segment, target) in pending - {key}
                for _, target in module.functions[key].targets()
                if (module.functions[key].segment, target) in module.functions
            )
        ]
        if not ready:
            ready = [min(pending, key=lambda key: len(module.functions[key].instructions))]
        for key in ready:
            order.append(module.functions[key])
            pending.discard(key)
    for function in order:
        called = sorted(
            {
                module.functions[(function.segment, target)].name
                for kind, target in function.targets()
                if kind == "call" and (function.segment, target) in module.functions
            }
        )
        users = sorted({caller.name for caller in callers.get(function.key, [])})
        print(
            f"{function.label()} {function.name} ins={len(function.instructions)} "
            f"callers={','.join(users) or '-'} calls={','.join(called) or '-'}"
        )
    print(f"{len(order)} unnamed of {len(module.functions)}")


def annotations(module: str) -> tuple[dict[int, str], dict[int, list[str]]]:
    data: dict[int, str] = {}
    comments: dict[int, list[str]] = collections.defaultdict(list)
    path = names_file(module)
    if not path.exists():
        return data, comments
    for line in path.read_text(encoding="utf-8").splitlines():
        columns = line.split("\t")
        if line.startswith("#") or len(columns) < 3:
            continue
        offset = int(columns[0].split(":")[-1], 16)
        text = columns[3] if len(columns) > 3 else ""
        if columns[1] == "data":
            data[offset] = columns[2] + (f" ({text})" if text else "")
        elif columns[1] in ("comment", "label"):
            comments[offset].append(text if columns[1] == "comment" else f"{columns[2]}: {text}")
    return data, comments


def service_names(modules: dict[str, Module]) -> dict[str, dict[int, str]]:
    jo = modules.get("JO.EXE")
    if jo is None or not JO_IMAGE.exists():
        return {}
    data = JO_IMAGE.read_bytes()
    image = data[struct.unpack_from("<H", data, 8)[0] * 16 :]
    tables = {}
    for suffix, (offset, count) in SERVICE_TABLES.items():
        names = {}
        for number in range(count):
            target = struct.unpack_from("<H", image, offset + number * 2)[0]
            handler = jo.functions.get((0, target))
            names[number] = handler.name if handler else f"{target:04x}"
        tables[suffix] = names
    return tables


def object_fields() -> dict[int, str]:
    fields = {}
    for line in OBJECT_TYPE.read_text(encoding="utf-8").splitlines():
        columns = line.split("\t")
        if not line.startswith("#") and len(columns) >= 3:
            fields[int(columns[0], 16)] = columns[2]
    return fields


def ai_handler_slots(image: bytes, *, valid: set[int]) -> dict[int, list[tuple[int, int, int]]]:
    table = struct.unpack_from("<H", image, 2)[0]
    pointers: list[int] = []
    while table + len(pointers) * 2 < min(pointers, default=len(image)):
        pointer = struct.unpack_from("<H", image, table + len(pointers) * 2)[0]
        if not table < pointer < len(image):
            break
        pointers.append(pointer)
    slots: dict[int, list[tuple[int, int, int]]] = collections.defaultdict(list)
    array = min(pointers, default=len(image))
    end = array
    while end + 1 < len(image) and 0x16 <= struct.unpack_from("<H", image, end)[0] < len(image):
        end += 2
    above = [struct.unpack_from("<H", image, cursor)[0] for cursor in range(array, end, 2)]
    end = min([end] + [value for value in above if value > table])
    for cursor in range(array, end - 1, 2):
        value = struct.unpack_from("<H", image, cursor)[0]
        if value not in valid:
            continue
        exact = [group for group, pointer in enumerate(pointers) if pointer == cursor]
        if exact:
            slots[value].append((exact[0], 0, cursor))
            continue
        before = max((pointer, group) for group, pointer in enumerate(pointers) if pointer < cursor)
        slots[value].append((before[1], (cursor - before[0]) // 2, cursor))
    return slots


def ai_names(module: Module, *, write: bool) -> None:
    valid = {address for segment, address in module.functions if segment == 0}
    slots = ai_handler_slots((UNPACKED_DIR / module.file).read_bytes(), valid=valid)
    taken = {function.name for function in module.functions.values()}
    lines = []
    for address, places in sorted(slots.items()):
        function = module.functions.get((0, address))
        if function is None or function.named:
            continue
        group, state, _ = min(places, key=lambda place: (place[1], place[0]))
        name = f"ai_type{group:02x}" if state == 0 else f"ai_type{group:02x}_s{state}"
        if name in taken:
            continue
        taken.add(name)
        where = ", ".join(f"type {g:02X}h state {k}" for g, k, _ in sorted(places))
        lines.append(f"{function.label()}\tfunc\t{name}\tAI handler ({where}). (structural name)")
    print(f"{module.file}: {len(lines)} AI handler names")
    if write and lines:
        append_names(module.file, lines)


def show(module: Module, function: Function, *, services: dict[str, dict[int, str]]) -> None:
    callers = callers_of(module)
    fields = object_fields() if module.file.startswith("ENEMY") else {}
    data, comments = annotations(module.file)
    users = sorted({caller.name for caller in callers.get(function.key, [])})
    print(f"== {module.file} {function.label()} {function.name} (callers: {', '.join(users) or '-'})")
    ax_value = None
    for address, text in function.instructions:
        notes = []
        match = BRANCH.match(text)
        if match or text.startswith("jmp 0x"):
            target = int(match.group(2) if match else text[4:], 16)
            callee = module.functions.get((function.segment, target))
            if callee and callee.key != function.key:
                notes.append(callee.name)
                table = next((names for suffix, names in services.items() if callee.name.endswith(suffix)), None)
                if table is not None and ax_value is not None and not comments.get(address):
                    notes.append(f"service {ax_value:02X}h {table.get(ax_value, '?')}")
        constant = re.fullmatch(r"mov ax, (0x[0-9a-f]+|\d+)", text)
        ax_value = int(constant.group(1), 0) if constant else (ax_value if not text.startswith("call") else None)
        for constant in re.findall(r"\[0x([0-9a-f]+)\]", text):
            if int(constant, 16) in data:
                notes.append(data[int(constant, 16)])
        for register, offset in re.findall(r"\[(si|di)(?: \+ (0x[0-9a-f]+|\d+))?\]", text):
            field = fields.get(int(offset, 0) if offset else 0)
            if field:
                notes.append(f"{register}.{field}")
        notes += comments.get(address, [])
        print(f"  {address:04x}: {text}{'  ; ' + '; '.join(notes) if notes else ''}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Names for recompiled functions (reads the generated C files).")
    commands = parser.add_subparsers(dest="command", required=True)
    propagate_command = commands.add_parser(
        "propagate", help="name unnamed functions with the same code as a named one"
    )
    propagate_command.add_argument("--write", action="store_true", help="append the names to the names files")
    todo_command = commands.add_parser("todo", help="unnamed functions of a module, callees first")
    todo_command.add_argument("module", help="file name, e.g. JO.EXE")
    data_todo_command = commands.add_parser("data-todo", help="unnamed fixed DS data addresses of a module, by use")
    data_todo_command.add_argument("module", help="file name, e.g. JO.EXE")
    show_command = commands.add_parser("show", help="listing of functions with callee names")
    show_command.add_argument("module")
    show_command.add_argument("functions", nargs="+", help="names or [SEG:]OFF addresses")
    commands.add_parser("stats", help="named and unnamed functions per module")
    ai_command = commands.add_parser("ai-names", help="structural names for the AI handlers of ENEMYn overlays")
    ai_command.add_argument("--write", action="store_true", help="append the names to the names files")
    args = parser.parse_args()
    modules = load_modules()
    if args.command == "propagate":
        propagate(modules, write=args.write)
    elif args.command == "ai-names":
        for name in sorted(modules):
            if name.startswith("ENEMY"):
                ai_names(modules[name], write=args.write)
    elif args.command == "stats":
        total = unnamed = 0
        for module in modules.values():
            count = sum(1 for function in module.functions.values() if not function.named)
            print(f"{module.file:14} {len(module.functions):5} functions {count:5} unnamed")
            total += len(module.functions)
            unnamed += count
        print(f"{'all':14} {total:5} functions {unnamed:5} unnamed")
    else:
        module = modules.get(args.module)
        if module is None:
            parser.error(f"no generated module {args.module}; known: {' '.join(sorted(modules))}")
        if args.command == "todo":
            todo(module)
        elif args.command == "data-todo":
            data_todo(module)
        else:
            services = service_names(modules)
            for text in args.functions:
                function = module.by_name(text)
                if function is None:
                    print(f"{text}: not found", file=sys.stderr)
                    continue
                show(module, function, services=services)
    return 0


if __name__ == "__main__":
    sys.exit(main())
